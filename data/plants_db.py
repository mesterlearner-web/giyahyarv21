def search_plants(query):
    query = query.lower()
    results = []
    for plant in PLANTS_DATA:
        if (query in plant["name"].lower() or 
            query in plant.get("scientific_name", "").lower() or
            query in plant.get("description", "").lower() or
            query in plant.get("category", "").lower()):
            results.append(plant)
    return results

